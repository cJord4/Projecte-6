# Mòdul per convertir segons a hores, minuts, etc.

def segons_a_minuts(segons):
    return segons / 60

def segons_a_hores(segons):
    return segons / 3600

def minuts_a_segons(minuts):
    return minuts * 60

def hores_a_segons(hores):
    return hores * 3600